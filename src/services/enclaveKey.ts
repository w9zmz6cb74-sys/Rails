/**
 * Enclave Signer Key Manager
 *
 * Automatically detects ENCLAVE_SIGNER_KEY in the environment or falls back
 * to dynamically generating a random 64-character hex key in local state.
 * This guarantees seamless preview and mock transaction signing without
 * prompting the user for environment variables during testing.
 */

let inMemoryEnclaveKey: string | null = null;
let isKeyAutoGenerated: boolean = false;

/**
 * Returns a 64-character hexadecimal key (256-bit entropy).
 */
export function getEnclaveSignerKey(): string {
  // 1. Check Vite environment variable if configured
  const envKey =
    typeof import.meta !== 'undefined' &&
    (import.meta.env?.VITE_ENCLAVE_SIGNER_KEY ||
      import.meta.env?.ENCLAVE_SIGNER_KEY ||
      import.meta.env?.VITE_ENCLAVE_SIGNER_SECRET);

  if (envKey && typeof envKey === 'string' && envKey.trim().length >= 32) {
    isKeyAutoGenerated = false;
    return envKey.trim();
  }

  // 2. Check in-memory cached key
  if (inMemoryEnclaveKey && inMemoryEnclaveKey.length === 64) {
    return inMemoryEnclaveKey;
  }

  // 3. Check sessionStorage so key remains consistent across view switches
  try {
    const sessionKey = sessionStorage.getItem('agentrails_enclave_mock_key');
    if (sessionKey && sessionKey.length === 64) {
      inMemoryEnclaveKey = sessionKey;
      isKeyAutoGenerated = true;
      return inMemoryEnclaveKey;
    }
  } catch {
    // SessionStorage may be restricted in sandboxed iframes
  }

  // 4. Generate random 64-character hex key (32 random bytes)
  const bytes = new Uint8Array(32);
  if (typeof crypto !== 'undefined' && crypto.getRandomValues) {
    crypto.getRandomValues(bytes);
  } else {
    for (let i = 0; i < 32; i++) {
      bytes[i] = Math.floor(Math.random() * 256);
    }
  }

  const generatedHex = Array.from(bytes)
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');

  inMemoryEnclaveKey = generatedHex;
  isKeyAutoGenerated = true;

  try {
    sessionStorage.setItem('agentrails_enclave_mock_key', generatedHex);
  } catch {}

  return inMemoryEnclaveKey;
}

/**
 * Returns diagnostic metadata about the active enclave signer key.
 */
export function getEnclaveKeyInfo(): {
  key: string;
  isAutoGenerated: boolean;
  keyPreview: string;
} {
  const key = getEnclaveSignerKey();
  return {
    key,
    isAutoGenerated: isKeyAutoGenerated,
    keyPreview: `${key.slice(0, 10)}...${key.slice(-8)}`,
  };
}

/**
 * Generates a mock EIP-712 UserOperation signature using the active enclave key.
 */
export function generateMockEnclaveSignature(dataToSign: string): string {
  const key = getEnclaveSignerKey();
  // Simple deterministic hash simulation for client-side preview
  let hash = 0;
  const combined = `${key}:${dataToSign}`;
  for (let i = 0; i < combined.length; i++) {
    hash = (hash << 5) - hash + combined.charCodeAt(i);
    hash |= 0;
  }
  const hexPart = Math.abs(hash).toString(16).padStart(8, '0');
  return `0x7579${key.slice(0, 56)}${hexPart}1b`;
}
